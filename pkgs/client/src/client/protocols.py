from ssl import PROTOCOL_SSLv2
from typing import Protocol, List, Dict, Any, Callable, Awaitable
from .models import Guild, Channel, Message, User

class AuthProtocol(Protocol):
    # Active
    async def login_with_password(self, email: str, password: str) -> Dict[str, Any]: ...
    async def submit_totp(self, ticket: str, code: str) -> str: ...
    async def login_with_token(self, token: str) -> bool: ...
    async def connect(self) -> None: ...
    async def logoff(self) -> None: ...
    # Deferred
    async def login_with_qr(self) -> str: ...

class RelationsProtocol(Protocol):
    # Active
    async def get_guilds(self) -> List[Guild]: ...
    async def get_channels(self, guild_id: str) -> List[Channel]: ...
    async def get_dms(self) -> List[Channel]: ...
    # Deferred
    async def get_friends(self) -> List[User]: ...
    async def add_friend(self, user_id: str) -> bool: ...
    async def remove_friend(self, user_id: str) -> bool: ...
    async def join_guild(self, invite_code: str) -> Guild: ...
    async def leave_guild(self, guild_id: str) -> bool: ...

class MessagingProtocol(Protocol):
    # Active
    async def send_message(self, channel_id: str, content: str) -> bool: ...
    def on_message_received(self, callback: Callable[[Message], Awaitable[None]]) -> None: ...
    # Deferred
    async def edit_message(self, channel_id: str, message_id: str, new_content: str) -> bool: ...
    async def delete_message(self, channel_id: str, message_id: str) -> bool: ...

class ClientProtocol(Protocol):
    """The main governor contract."""
    auth: AuthProtocol
    relations: RelationsProtocol
    messaging: MessagingProtocol
